/**
 * อัตราส่วนเป็นเปอร์เซ็นต์ที่ใส่คอลัมน์ได้เสมอ
 *
 * ตอนที่ "รายได้" ของ P&L รายแผนกยังมาจากแถว REVENUE ที่คนคีย์เองใน `cost_entries`
 * ตัวเลขมันใหญ่กว่าต้นทุนอยู่แล้ว อัตรากำไรจึงอยู่ในหลักสิบเสมอ พอเฟส 4 เปลี่ยนไป
 * ใช้ยอดขายจริงจากสมุด แผนกที่ยังไม่มีรายได้เข้าระบบแต่มีต้นทุนเต็มเดือนให้ค่าอย่าง
 * -2,604% ซึ่งเป็นค่าที่ถูกต้อง แต่ `Decimal(5,2)` เก็บได้แค่ ±999.99 การปิดงวดจึง
 * ล้มทั้งงวดด้วย error ของฐานข้อมูลที่ไม่ได้บอกว่าเกิดอะไรขึ้น
 *
 * คอลัมน์ถูกขยายเป็น `Decimal(10,2)` แล้ว ที่นี่เป็นด่านสุดท้ายกันกรณีสุดขั้ว
 * (ขายได้ 1 สตางค์ในแผนกที่มีต้นทุนหลักแสน) ไม่ให้การปิดงวดทั้งเดือนพังเพราะ
 * ตัวเลขประกอบตัวเดียว — ตัวตั้งกับตัวหารยังถูกเก็บเต็มความละเอียดในคอลัมน์ของมันเอง
 * ผู้อ่านจึงคำนวณกลับได้เสมอ
 */
import { round2 } from '@/common/utils/bangkok-day.util';

/** ขอบของ `Decimal(10,2)` */
export const PERCENT_LIMIT = 99_999_999.99;

const clamp = (value: number): number =>
  Math.min(PERCENT_LIMIT, Math.max(-PERCENT_LIMIT, value));

/**
 * `part / whole` เป็นเปอร์เซ็นต์
 *
 * ฐานเป็นศูนย์หรือติดลบคืน 0 — "ไม่มีฐานให้เทียบ" ไม่ใช่ "อัตราเป็นอนันต์"
 */
export const percentOf = (part: number, whole: number): number =>
  whole > 0 ? clamp(round2((part / whole) * 100)) : 0;
