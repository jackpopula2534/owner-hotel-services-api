-- จำนวนชั้นของที่พักไม่เคยถูกกำหนดไว้ที่ไหนเลย
--
-- ก่อนหน้านี้ "ชั้น" มีที่เก็บที่เดียวคือ rooms.floor ซึ่งพิมพ์เองทีละห้อง
-- หน้าจอที่ต้องแสดงรายชื่อชั้นจึงมีสองพฤติกรรมปนกัน: บางที่ไล่จากห้องจริง
-- (แผนผังห้อง / room-heatmap) บางที่ฮาร์ดโค้ดชั้น 1-5 ทิ้งไว้ (กระดานแม่บ้าน)
-- โรงแรมที่มี 4 ห้องอยู่ชั้นเดียวจึงเห็นปุ่มชั้น 2-5 ที่กดแล้วว่างเปล่าเสมอ
--
-- คอลัมน์นี้คือแหล่งความจริงของ "ที่พักหลังนี้มีกี่ชั้น" — ตัวเลือกชั้นตอนเพิ่มห้อง
-- และตัวกรองชั้นทุกหน้าจออ่านจากค่านี้
ALTER TABLE `properties` ADD COLUMN `floors` INT NOT NULL DEFAULT 1;

-- ที่พักเดิมมีห้องอยู่แล้ว — เดาค่าเริ่มต้นจากชั้นสูงสุดที่มีห้องอยู่จริง
-- เพื่อไม่ให้ห้องที่บันทึกไว้แล้วหลุดออกนอกช่วงที่ตั้งใหม่
UPDATE `properties` `p`
SET `p`.`floors` = GREATEST(
  1,
  COALESCE((SELECT MAX(`r`.`floor`) FROM `rooms` `r` WHERE `r`.`propertyId` = `p`.`id`), 1)
);
